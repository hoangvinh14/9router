import assert from 'node:assert/strict';
import { compare, collect } from './compare-baseline.mjs';
const file = 'tests/unit/control.test.js';
const make = (status = 'passed') => ({ testResults: [{ name: `/checkout/9router/${file}`, status, message: '', assertionResults: [{ fullName: 'control body', status, failureMessages: [] }] }] });
const old = make();
const checks = {};
checks.identity = [...collect(old, [file], '/checkout/9router').keys()][0] === file;
checks.unchanged = compare(old, make(), [file], '/checkout/9router').exit === 0;
checks.passToFail = compare(old, make('failed'), [file], '/checkout/9router').exit === 1;
checks.missingSuite = compare(old, { testResults: [] }, [file], '/checkout/9router').exit === 2;
const missing = make(); missing.testResults[0].assertionResults = [];
checks.collectionUnreached = compare(old, missing, [file], '/checkout/9router').exit === 2;
const skipped = make(); skipped.testResults[0].assertionResults[0].status = 'pending';
checks.skippedBody = compare(old, skipped, [file], '/checkout/9router').exit === 2;
const hook = make('failed'); hook.testResults[0].assertionResults[0].failureMessages = ['Hook timed out in beforeAll'];
checks.hookUnreached = compare(old, hook, [file], '/checkout/9router').exit === 2;
const foreign = make(); foreign.testResults[0].name = '/foreign/tests/unit/control.test.js';
checks.foreignIdentity = compare(old, foreign, [file], '/checkout/9router').exit === 2;
const renamed = make(); renamed.testResults[0].assertionResults[0].fullName = 'different body';
checks.missingAssertion = compare(old, renamed, [file], '/checkout/9router').exit === 2;
for (const [name, passed] of Object.entries(checks)) assert.equal(passed, true, name);
console.log(JSON.stringify({ checks, passed: Object.keys(checks).length }));
